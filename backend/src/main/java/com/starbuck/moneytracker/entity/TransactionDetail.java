package com.starbuck.moneytracker.entity;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.List;
import java.util.stream.Collectors;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import jakarta.persistence.Id;
import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;

@Entity(name = "transaction_details")
public class TransactionDetail {

    /**
     * Ez a neve a transactionDetailnek, hogyha a user összegezve adja meg a
     * tranzakció összeget
     */
    public static final String DEFAULT_DETAIL_NAME = "sum";

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false)
    private String name;

    @Column(nullable = false, precision = 10, scale = 2)
    private BigDecimal price;

    @Column(nullable = true, precision = 10, scale = 2)
    private BigDecimal weight;

    @Column(nullable = true, precision = 10, scale = 2)
    private BigDecimal unitPrice;

    // TODO category field

    @CreationTimestamp
    private LocalDateTime createdAt;

    @UpdateTimestamp
    private LocalDateTime updatedAt;

    @ManyToOne
    @JoinColumn(name = "transaction_id", nullable = false)
    private Transaction transaction;

    @OneToMany(mappedBy = "transactionDetail", cascade = CascadeType.REMOVE)
    private List<TransactionDetailCategory> categoryLinks;

    /**
     * Frontenden egyszerű (csak price van megadva), vagy komplex (egységár és
     * mennyiség is meg van adva) árazási módot használunk
     */
    public boolean isComplexPriceMode() {
        return weight != null && unitPrice != null;
    }

    /**
     * Tételhez kapcsolt kategória azonosítók listájával tér vissza
     * TODO ez lehet nem helyes, hogy entitásban van, mert lazy load esetén categoryLinks nincs betöltve
     * 
     * @return
     */
    public List<Long> getCategoryIds() {
        return this.categoryLinks.stream().map((categoryLink) -> categoryLink.getCategory().getId())
                .collect(Collectors.toList());
    }

    // AUTOGENERATED

    public TransactionDetail() {
    }

    public TransactionDetail(Long id, String name, BigDecimal price, BigDecimal weight, BigDecimal unitPrice,
            Transaction transaction) {
        this.id = id;
        this.name = name;
        this.price = price;
        this.weight = weight;
        this.unitPrice = unitPrice;
        this.transaction = transaction;
    }

    public TransactionDetail(String name, BigDecimal price, BigDecimal weight, BigDecimal unitPrice,
            Transaction transaction) {
        this.name = name;
        this.price = price;
        this.weight = weight;
        this.unitPrice = unitPrice;
        this.transaction = transaction;
    }

    public TransactionDetail(String name, BigDecimal price) {
        this.name = name;
        this.price = price;
    }

    public TransactionDetail(String name, BigDecimal weight, BigDecimal unitPrice) {
        this.name = name;
        this.unitPrice = unitPrice;
        this.weight = weight;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public BigDecimal getPrice() {
        return price;
    }

    public void setPrice(BigDecimal price) {
        this.price = price;
    }

    public BigDecimal getWeight() {
        return weight;
    }

    public void setWeight(BigDecimal weight) {
        this.weight = weight;
    }

    public BigDecimal getUnitPrice() {
        return unitPrice;
    }

    public void setUnitPrice(BigDecimal unitPrice) {
        this.unitPrice = unitPrice;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(LocalDateTime updatedAt) {
        this.updatedAt = updatedAt;
    }

    public Transaction getTransaction() {
        return transaction;
    }

    public void setTransaction(Transaction transaction) {
        this.transaction = transaction;
    }

    public List<TransactionDetailCategory> getCategoryLinks() {
        return categoryLinks;
    }

    public void setCategoryLinks(List<TransactionDetailCategory> categoryLinks) {
        this.categoryLinks = categoryLinks;
    }
}
